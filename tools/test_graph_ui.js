const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'GRAPH_UI.h'), 'utf8').split('R"graphjs(')[1].split(')graphjs"')[0];
const context = {module:{exports:{}}};
vm.runInNewContext(source, context);
const graph = context.module.exports;
const day = 20000, start = day*86400;
const points = graph.pointsFromDays([{day,step:60,values:[0,100,null,200,300]}],start,start+240);
assert.equal(points.length,5);
assert.equal(points[0].value,0, 'zero production must not become missing');
assert.equal(graph.segments(points).length,2, 'missing readings must break the line');
assert.equal(graph.segments([{time:0,value:1,step:60},{time:3600,value:2,step:60}]).length,2);
assert.equal(graph.pointsFromDays([{day,step:60,values:[1,2,3]}],start+60,start+60).length,1);
assert.equal(graph.niceMax(0),100);
assert.equal(graph.niceMax(2800),5000);
const svg = graph.chartSvg(points,start,start+300);
assert(!svg.includes('NaN')&&!svg.includes('Infinity'));
assert.equal((svg.match(/stroke="#47dfb0"/g)||[]).length,2);
assert(svg.includes('aria-label="Power production in watts over time"'));
assert(graph.chartSvg([{time:start,value:10,step:60}],start,start+300).includes('<circle'));
assert(!graph.chartSvg([{time:start,value:null,step:60}],start,start+300).includes('NaN'));
const routes = fs.readFileSync(path.join(root,'ASYSERVER.ino'),'utf8');
assert(routes.match(/server\.on\("\/api\/graph\/settings", HTTP_POST,[\s\S]*?authenticate\("admin", pswd\)/));
assert(source.includes('aria-label="Confirm clearing detailed history"'),'clearing requires an explicit confirmation panel');
assert(source.includes('for (const day of status.days.filter'),'fetch days sequentially');
assert(!source.includes('localStorage'),'disabled feature must not leave browser history storage');
console.log('Power graph rendering, gaps, range clipping and route protection passed.');
